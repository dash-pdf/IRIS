"""
poc_voice_loop.py
-----------------
Phase 0 Proof of Concept — IRIS Voice Loop Validation.

What this script does:
1. Loads API keys from .env.
2. Opens an ElevenLabs ConvAI session.
3. Listens for your voice via the microphone.
4. Receives and logs the STT transcript (what you said).
5. Logs IRIS's response (generated by the ElevenLabs agent configuration).
6. Plays the TTS response through the speakers.
7. Writes every turn to a Markdown archive file.
8. Prints latency numbers to the terminal.

What this script does NOT do yet:
- It does not call a custom LLM. IRIS's response comes from whatever
  system prompt and LLM you have configured in your ElevenLabs agent
  dashboard. For Phase 0, configure a simple echo or static response.
- It does not have a full UI, tray icon, or production error recovery.

Prerequisites:
1. Copy .env.example to .env and fill in:
   - ELEVENLABS_API_KEY
   - ELEVENLABS_AGENT_ID  (create an agent at elevenlabs.io/app/conversational-ai)
2. Run:
   python3 -m venv .venv
   source .venv/bin/activate
   pip install -r requirements.txt
3. Then run this script:
   python poc_voice_loop.py

Press Ctrl+C to end the session.
"""

from __future__ import annotations

import logging
import sys
import time
from pathlib import Path

# ── Configure logging before any imports that might log ──────────────────────
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s  %(levelname)-8s  %(name)s — %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger("iris.poc")


def main() -> None:
    # ── 1. Load configuration ─────────────────────────────────────────────
    try:
        from iris.core.config import load_config
        config = load_config(require_voice=True)
    except EnvironmentError as exc:
        logger.error("Configuration error: %s", exc)
        sys.exit(1)

    logger.info("IRIS Phase 0 PoC starting…")
    logger.info("Archive directory: %s", config.archive_dir)

    # ── 2. Open conversation archive ──────────────────────────────────────
    from iris.services.archive import ConversationArchive
    archive = ConversationArchive(
        archive_dir=config.archive_dir,
        persona_name=config.persona_name,
    )
    session_file = archive.open_session()
    logger.info("Session file: %s", session_file)
    print(f"\n✅ Session archive: {session_file}\n")

    # ── 3. Latency tracking ───────────────────────────────────────────────
    _turn_start: dict[str, float] = {}

    # ── 4. Define callbacks ───────────────────────────────────────────────

    def on_user_transcript(text: str) -> None:
        """Called when ElevenLabs finishes transcribing what you said."""
        _turn_start["t"] = time.perf_counter()
        print(f"\n🎤 You:   {text}")
        archive.write_turn("user", text)

    def on_assistant_response(text: str) -> None:
        """Called when IRIS's response text is available (before audio plays)."""
        elapsed_ms = 0
        if "t" in _turn_start:
            elapsed_ms = int((time.perf_counter() - _turn_start["t"]) * 1000)
        print(f"🤖 IRIS:  {text}")
        if elapsed_ms:
            print(f"   ⏱  Response latency: {elapsed_ms} ms")
        archive.write_turn("assistant", text)

    def on_error(message: str) -> None:
        """Called when ElevenLabs reports an error."""
        logger.error("Voice error: %s", message)
        print(f"\n⚠️  Error: {message}")
        archive.write_error(message)

    # ── 5. Start voice session ────────────────────────────────────────────
    from iris.adapters.voice_elevenlabs import ElevenLabsVoiceAdapter

    adapter = ElevenLabsVoiceAdapter(
        api_key=config.elevenlabs_api_key,
        agent_id=config.elevenlabs_agent_id,
        on_user_transcript=on_user_transcript,
        on_assistant_response=on_assistant_response,
        on_error=on_error,
    )

    print("🎙  Speak now. Press Ctrl+C to end the session.\n")

    try:
        adapter.start()
    except KeyboardInterrupt:
        print("\n\nSession ended by user.")
    finally:
        # ── 6. Clean up ───────────────────────────────────────────────────
        adapter.stop()
        archive.close_session()
        print(f"\n📄 Conversation saved to: {session_file}")
        logger.info("Phase 0 PoC complete.")


if __name__ == "__main__":
    main()

